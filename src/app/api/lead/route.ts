import { NextRequest, NextResponse } from "next/server";
import { isValidIndianPhone } from "@/lib/validation";

// In-memory rate limiting map: IP -> array of request timestamps (epoch ms)
// 5 requests per minute per IP address
const rateLimitMap = new Map<string, number[]>();
const RATE_LIMIT_WINDOW_MS = 60 * 1000; // 1 minute
const MAX_REQUESTS_PER_WINDOW = 5;

function isRateLimited(ip: string): boolean {
  const now = Date.now();
  const timestamps = rateLimitMap.get(ip) || [];

  // Filter timestamps within the current sliding window
  const recentTimestamps = timestamps.filter((time) => now - time < RATE_LIMIT_WINDOW_MS);

  if (recentTimestamps.length >= MAX_REQUESTS_PER_WINDOW) {
    rateLimitMap.set(ip, recentTimestamps);
    return true;
  }

  recentTimestamps.push(now);
  rateLimitMap.set(ip, recentTimestamps);
  return false;
}

export async function POST(req: NextRequest) {
  try {
    // 1. Identify Client IP for rate limiting
    const forwardedFor = req.headers.get("x-forwarded-for");
    const ip = forwardedFor ? forwardedFor.split(",")[0].trim() : "unknown-ip";

    if (isRateLimited(ip)) {
      return NextResponse.json(
        { ok: false, error: "Too many requests. Please wait a minute before submitting again." },
        { status: 429 }
      );
    }

    // 2. Parse request JSON body
    const body = await req.json().catch(() => null);
    if (!body || typeof body !== "object") {
      return NextResponse.json(
        { ok: false, error: "Invalid JSON payload" },
        { status: 400 }
      );
    }

    // 3. Honeypot check: if "company" is filled, silently ignore and return success
    const honeypot = String(body.company || "").trim();
    if (honeypot.length > 0) {
      return NextResponse.json({ ok: true, message: "Request received" }, { status: 200 });
    }

    // 4. Server-side validation and trimming
    const name = String(body.name || "").trim().slice(0, 80);
    const phone = String(body.phone || "").trim().slice(0, 20);
    const project = String(body.project || "").trim().slice(0, 120);
    const rawSource = String(body.source || "contact").trim().toLowerCase();
    const source = ["hero", "contact", "channel-partner", "cp-form"].includes(rawSource)
      ? rawSource
      : "contact";
    const microMarket = String(body.microMarket || "").trim().slice(0, 80);
    const unsoldUnits = String(body.unsoldUnits || "").trim().slice(0, 50);
    const scope = String(body.scope || "").trim().slice(0, 100);
    const overview = String(body.overview || "").trim().slice(0, 1000);

    if (name.length < 2) {
      return NextResponse.json(
        { ok: false, error: "Name must be at least 2 characters" },
        { status: 400 }
      );
    }

    if (!isValidIndianPhone(phone)) {
      return NextResponse.json(
        { ok: false, error: "Please enter a valid 10-digit Indian phone number" },
        { status: 400 }
      );
    }

    if (project.length < 2) {
      return NextResponse.json(
        { ok: false, error: "Project or firm name must be at least 2 characters" },
        { status: 400 }
      );
    }

    // 5. Read environment variables (server-side only)
    const scriptUrl = process.env.GOOGLE_SCRIPT_URL;
    const scriptSecret = process.env.GOOGLE_SCRIPT_SECRET;

    if (!scriptUrl || !scriptSecret) {
      console.error(
        "[API/LEAD ERROR] Missing environment variables: GOOGLE_SCRIPT_URL or GOOGLE_SCRIPT_SECRET is undefined."
      );
      return NextResponse.json(
        {
          ok: false,
          error: "Our lead database is temporarily unavailable. Please call or WhatsApp our advisory team directly.",
        },
        { status: 503 }
      );
    }

    // 6. Forward payload to Google Apps Script Web App
    // Note: Date & Time are generated by Apps Script in IST; website does not send them.
    // Fields missing from a form (e.g. Hero form) are sent as empty strings for empty sheet cells.
    const leadPayload = {
      secret: scriptSecret,
      source,
      name,
      phone,
      project,
      microMarket: microMarket || "",
      unsoldUnits: unsoldUnits || "",
      scope: scope || "",
      overview: overview || "",
    };

    // Google Apps Script answers with 302 redirect by default; follow redirects automatically
    const forwardResponse = await fetch(scriptUrl, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify(leadPayload),
      redirect: "follow",
    });

    if (!forwardResponse.ok) {
      console.error(
        `[API/LEAD ERROR] Google Script responded with status ${forwardResponse.status}`
      );
      return NextResponse.json(
        {
          ok: false,
          error: "Unable to save your request right now. Please call or WhatsApp our advisory team directly.",
        },
        { status: 502 }
      );
    }

    const scriptResult = await forwardResponse.json().catch(() => null);

    if (scriptResult && scriptResult.ok === true) {
      return NextResponse.json({ ok: true }, { status: 200 });
    } else {
      console.error("[API/LEAD ERROR] Google Script returned error response:", scriptResult);
      return NextResponse.json(
        {
          ok: false,
          error: scriptResult?.error || "Unable to save your request right now. Please call or WhatsApp our advisory team directly.",
        },
        { status: 502 }
      );
    }
  } catch (error) {
    console.error("[API/LEAD ERROR] Unexpected lead processing failure:", error);
    return NextResponse.json(
      {
        ok: false,
        error: "An unexpected error occurred. Please call or WhatsApp our advisory team directly.",
      },
      { status: 500 }
    );
  }
}
